// Writes .github/ISSUE_TEMPLATE/website-text.yml from scripts/lib/content-fields.mjs
import { writeFile } from 'node:fs/promises'
import { CONTENT_FIELDS } from './lib/content-fields.mjs'

const yml = `# Generated by scripts/build-content-form.mjs. Edit scripts/lib/content-fields.mjs instead.
name: Website text (change a text)
description: Pick a text on the site and write what it should say, in Finnish, English or both.
title: "Text: "
labels: ["website-text"]
body:
  - type: markdown
    attributes:
      value: |
        Choose the text, then write the new version. Leave a language empty to keep it as it is.
        For lists, separate words with commas. For longer texts, leave an empty line between paragraphs.
  - type: dropdown
    id: which
    attributes:
      label: Which text
      options:
${CONTENT_FIELDS.map((f) => `        - "${f.label.replace(/"/g, '\\"')}"`).join('\n')}
    validations:
      required: true
  - type: textarea
    id: fi
    attributes:
      label: New Finnish text
  - type: textarea
    id: en
    attributes:
      label: New English text
  - type: checkboxes
    id: reset
    attributes:
      label: Undo
      options:
        - label: Put back the original text (for the languages left empty, or both if both are empty)
`
await writeFile(new URL('../.github/ISSUE_TEMPLATE/website-text.yml', import.meta.url), yml)
console.log(`Wrote website-text.yml with ${CONTENT_FIELDS.length} texts`)
